"""## 16. Matching Feature Engineering
Build features measuring how well each resume matches its job description.

**Available matching signals:**
- `skills` (resume) vs `skills_required` (job) → Jaccard + cosine
- `related_skils_in_job` vs `skills_required` → Jaccard + cosine  
- `positions` vs `job_position_name` → cosine
- `career_objective` vs `responsibilities.1` → cosine
- Count features: num_skills, num_positions, etc.
- Experience: total_years_experience, recency_education_years

**Note:** `responsibilities` == `responsibilities.1` (same column, job-side only).
Resume work descriptions are absent from this dataset.
"""

# ── Helpers ───────────────────────────────────────────────────────────────────
def list_to_str(val):
    """Flatten list to lowercase string for TF-IDF."""
    if isinstance(val, (list, tuple)): # Updated to handle tuples as well
        return ' '.join(str(i).lower() for i in val
                        if str(i).lower() not in ('none','nan','n/a','not specified',''))
    return str(val).lower() if pd.notna(val) else ''

def jaccard(a, b):
    sa = set(list_to_str(a).split())
    sb = set(list_to_str(b).split())
    if not (sa | sb): return 0.0
    return len(sa & sb) / len(sa | sb)

# ── Jaccard overlap features ───────────────────────────────────────────────────
df['skill_jaccard']          = df.apply(lambda r: jaccard(r['skills'], r['skills_required']), axis=1)
df['related_skill_jaccard']  = df.apply(lambda r: jaccard(r['related_skils_in_job'], r['skills_required']), axis=1)
df['position_title_jaccard'] = df.apply(lambda r: jaccard(r['positions'], r['job_position_name']), axis=1)

# ── Count features ─────────────────────────────────────────────────────────────
df['num_skills']         = df['skills'].apply(lambda x: len(x) if isinstance(x, (list, tuple)) else 0) # Updated
df['num_positions']      = df['positions'].apply(lambda x: len(x) if isinstance(x, (list, tuple)) else 0) # Updated
df['num_related_skills'] = df['related_skils_in_job'].apply(lambda x: len(x) if isinstance(x, (list, tuple)) else 0) # Updated
df['num_degrees']        = df['degree_names'].apply(lambda x: len(x) if isinstance(x, (list, tuple)) else 0) # Updated

# ── TF-IDF cosine similarity features ─────────────────────────────────────────
text_pairs = [
    ('skills',               'responsibilities.1', 'skill_vs_jobresp_cos'),
    ('related_skils_in_job', 'responsibilities.1', 'relskill_vs_jobresp_cos'),
    ('positions',            'job_position_name',  'position_vs_jobtitle_cos'),
    ('career_objective',     'responsibilities.1', 'objective_vs_jobresp_cos'),
]

for col_a, col_b, feat in text_pairs:
    if col_a not in df.columns or col_b not in df.columns: continue
    texts_a = df[col_a].apply(list_to_str)
    texts_b = df[col_b].apply(list_to_str)
    tfidf = TfidfVectorizer(stop_words='english', max_features=5000)
    tfidf.fit(pd.concat([texts_a, texts_b]))
    va = tfidf.transform(texts_a)
    vb = tfidf.transform(texts_b)
    df[feat] = [cosine_similarity(va[i], vb[i])[0][0] for i in range(len(df))]
    print(f"  {feat:<40} mean={df[feat].mean():.3f}  non-zero={( df[feat]>0).sum()}")

print("\nFeature engineering done ✔")

