JUNK_VALUES = {'none', 'nan', 'n/a', 'unknown', '', ' ', 'not specified'}

def to_clean_list(val):
    """Convert any format to a clean Python list of strings, handling newlines and commas."""
    if val is None or (isinstance(val, float) and np.isnan(val)):
        return []

    if isinstance(val, list):
        # If it's already a list, process each item, joining by comma first
        temp_s = ','.join(str(item).replace('\n', ',') for item in val)
    else:
        # If it's a string, replace newlines with commas for consistent parsing
        temp_s = str(val).strip().replace('\n', ',')

    if temp_s.lower() in JUNK_VALUES or not temp_s.strip(): # Check for empty or junk after replacement
        return []

    # Attempt ast.literal_eval if it looks like a list or tuple representation
    try:
        parsed = ast.literal_eval(temp_s)
        if isinstance(parsed, (list, tuple)): # <--- MODIFIED HERE to handle tuples as well
            # If successfully parsed as a list or tuple, process its elements
            all_sub_items = []
            for item in parsed:
                s_item = str(item).strip()
                # Split elements of the parsed list/tuple further by comma
                all_sub_items.extend([i.strip() for i in s_item.split(',') if i.strip().lower() not in JUNK_VALUES])
            return [item for item in all_sub_items if item] # Filter out empty strings
        # If ast.literal_eval returns a single non-list/non-tuple item (e.g., 'skill_name')
        return [str(parsed).strip()] if str(parsed).strip().lower() not in JUNK_VALUES else []
    except (ValueError, SyntaxError):
        pass # Not a stringified list/tuple, proceed with simple split

    # Fallback to splitting by comma (already handled newlines)
    return [i.strip() for i in temp_s.split(',')
            if i.strip().lower() not in JUNK_VALUES and i.strip()] # Filter out empty strings

