"""## 19. Sentence Embedding Features
Unlike TF-IDF which needs **exact word matches**, sentence embeddings understand
meaning — so *"Python developer"* ≈ *"software engineer"* even with zero shared words.

**Why this matters here:** Your TF-IDF features had mean similarity of ~0.02 because
resumes and job descriptions use different vocabulary. Embeddings fix this.

**Model used:** `all-MiniLM-L6-v2` — fast (~80 MB), runs on CPU, excellent quality.

```bash
pip install sentence-transformers   # run once if not installed
```

**Features created:**
| Feature | What it measures |
|---|---|
| `sem_full_sim` | Full resume text vs full job description |
| `sem_skills_sim` | Resume skills vs required skills |
| `sem_position_sim` | Past job titles vs target job title |
| `sem_objective_sim` | Career objective vs job responsibilities |
"""

